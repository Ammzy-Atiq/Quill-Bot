export interface ScamPhrase {
  /** Regex over the normalized (c1-collapsed, leet-folded) text, e.g. `free` becomes `fre`. */
  re: RegExp;
  severity: 3 | 4 | 5;
  reason: string;
  /** Only counts when the message also has a link, invite or attachment. */
  needsLink: boolean;
}

